"""Fail if this cudaq-edem version is on PyPI with different source contents.

PyPI never accepts a second upload of a version. If the version in the EDEM
CMake project is already published and the sources changed since, the new
wheels cannot be uploaded, and `pip install cudaq` would keep installing the old
code. The check compares the file contents of the source distribution built here
with the published one, since compiled wheels are not reproducible.
"""

import argparse
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
import sys
import tarfile
import time
import urllib.error
import urllib.request

PROJECT = "cudaq-edem"


def fetch(url, attempts=3):
    """Return the body of `url`, or None if it does not exist (HTTP 404)."""
    for attempt in range(1, attempts + 1):
        try:
            with urllib.request.urlopen(url, timeout=60) as response:
                return response.read()
        except urllib.error.HTTPError as error:
            if error.code == 404:
                return None
            failure = error
        except OSError as error:
            failure = error
        if attempt < attempts:
            time.sleep(5 * attempt * attempt)
    raise ConnectionError(f"Could not fetch {url}: {failure}")


def contents(archive):
    """Map each file of a source distribution to its digest.

    PKG-INFO is generated by the build backend, not part of the sources.
    """
    files = {}
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as source:
        for member in source.getmembers():
            if not member.isfile():
                continue
            relative = str(PurePosixPath(*PurePosixPath(member.name).parts[1:]))
            if relative != "PKG-INFO":
                files[relative] = hashlib.sha256(
                    source.extractfile(member).read()).hexdigest()
    return files


def check(sdist, index_url, allow_offline):
    sdist = Path(sdist)
    name = sdist.name.removesuffix(".tar.gz")
    prefix = "cudaq_edem-"
    if not name.startswith(prefix):
        raise ValueError(f"Not a cudaq-edem source distribution: {sdist}")
    version = name[len(prefix):]

    try:
        body = fetch(f"{index_url}/pypi/{PROJECT}/{version}/json")
        if body is None:
            print(f"{PROJECT} {version} is not on PyPI.")
            return 0
        published = [
            entry for entry in json.loads(body)["urls"]
            if entry["packagetype"] == "sdist"
        ]
        if len(published) != 1:
            print(f"::error::{PROJECT} {version} is on PyPI without a source "
                  "distribution, so its contents cannot be compared. Bump "
                  "CUDAQ_EDEM_VERSION in edem/CMakeLists.txt.")
            return 1
        archive = fetch(published[0]["url"])
        if archive is None:
            raise ConnectionError(f"Missing file {published[0]['url']}")
    except (ConnectionError, ValueError, KeyError) as error:
        if allow_offline:
            print(f"::warning::Skipping the PyPI version check: {error}")
            return 0
        print(f"::error::Could not check {PROJECT} {version} against PyPI: "
              f"{error}")
        return 1

    local, remote = contents(sdist.read_bytes()), contents(archive)
    changed = sorted(name for name in local.keys() & remote.keys()
                     if local[name] != remote[name])
    added = sorted(local.keys() - remote.keys())
    removed = sorted(remote.keys() - local.keys())
    if not (changed or added or removed):
        print(f"{PROJECT} {version} on PyPI has the same sources.")
        return 0
    for label, names in (("changed", changed), ("added", added), ("removed",
                                                                  removed)):
        for file in names:
            print(f"  {label}: {file}")
    print(f"::error::{PROJECT} {version} is already on PyPI with different "
          "sources. Bump CUDAQ_EDEM_VERSION in edem/CMakeLists.txt.")
    return 1


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sdist", help="the cudaq-edem source distribution")
    parser.add_argument("--index-url", default="https://pypi.org")
    parser.add_argument("--allow-offline",
                        action="store_true",
                        help="warn instead of failing if PyPI is unreachable")
    arguments = parser.parse_args()
    sys.exit(
        check(arguments.sdist, arguments.index_url.rstrip("/"),
              arguments.allow_offline))


if __name__ == "__main__":
    main()
