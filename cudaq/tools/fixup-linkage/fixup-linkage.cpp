/// The fixup-linkage tool is used to rewrite the LLVM IR produced by clang for
/// the classical compute code such that it can be linked correctly with the
/// LLVM IR that is generated for the quantum code.
///
/// We distinguish the 'host code' (generated by standard clang from the C++
/// source) from the 'generated code' (which contains the custom kernel stubs
/// that will redirect kernel launches into the CUDA-Q runtime). Every kernel
/// symbol has a definition in the generated code, which shadows the same
/// symbol definition in the host code. This script deletes the body of every
/// shadowed symbol in the host code, followed by DCE.
///
/// Explicitly DCE-ing keeps dead dependencies (e.g. the execution manager) out
/// of the object files produced by nvq++.
///
/// With `--warn-unresolved`, the tool also warns about CUDA-Q symbols that the
/// resulting object needs but that are not part of the C APIs exposed to code
/// generated by nvq++. Such an object cannot be loaded on its own (e.g. from
/// Python), where only those C APIs are available.

#include "llvm/Demangle/Demangle.h"
#include "llvm/IR/LLVMContext.h"
#include "llvm/IR/Module.h"
#include "llvm/IR/Verifier.h"
#include "llvm/IRReader/IRReader.h"
#include "llvm/Passes/PassBuilder.h"
#include "llvm/Support/SourceMgr.h"
#include "llvm/Support/raw_ostream.h"
#include "llvm/Transforms/IPO/GlobalDCE.h"
#include "llvm/Transforms/Utils/ModuleUtils.h"
#include <iostream>
#include <set>
#include <string>
#include <vector>

static std::unique_ptr<llvm::Module> parse(const char *file,
                                           llvm::LLVMContext &ctx) {
  llvm::SMDiagnostic err;
  auto mod = llvm::parseIRFile(file, err, ctx);
  if (!mod)
    err.print("fixup-linkage", llvm::errs());
  return mod;
}

/// Whether \p name is a CUDA-Q symbol that is provided by the CUDA-Q C APIs.
///
/// The valid symbols are identified by their prefix: `__cudaq_` (nvq++ C API),
/// `__quantum__` (QIR) and `__nvqir_` (NVQIR).
static bool isValidCudaqCAPISymbol(llvm::StringRef name) {
  for (llvm::StringRef prefix :
       {"__cudaq_", "__quantum__", "__nvqir_", "llvm."})
    if (name.starts_with(prefix))
      return true;
  if (name.starts_with("__nvqpp") || name.starts_with("cudaq"))
    return false;

  std::string demangled = llvm::demangle(name);
  // There are currently two C++ symbols we accept, related to setting targets
  // and disabling YAML parsing.
  for (llvm::StringRef allowed :
       {"cudaq::detail::YamlTargetConfigDisabler::YamlTargetConfigDisabler()",
        "cudaq::detail::TargetSetter::TargetSetter(char const*)"})
    if (demangled == allowed)
      return true;
  llvm::StringRef str = demangled;
  for (llvm::StringRef special : {"vtable for ", "typeinfo for ",
                                  "typeinfo name for ", "guard variable for "})
    str.consume_front(special);
  for (llvm::StringRef ns : {"cudaq::", "cudaq_internal::", "nvqir::"})
    if (str.starts_with(ns))
      return false;
  return true;
}

/// Warn about any CUDA-Q symbols left undefined by that are not provided by the
/// C APIs.
static void warnUnresolved(llvm::Module &host, llvm::Module &generated) {
  std::set<std::string> defined;
  std::set<std::string> declared;
  for (auto *mod : {&host, &generated})
    for (auto &gv : mod->global_values())
      (gv.isDeclaration() ? declared : defined).insert(gv.getName().str());

  std::set<std::string> unresolved;
  for (auto &name : declared)
    if (!defined.count(name) && !isValidCudaqCAPISymbol(name))
      unresolved.insert(llvm::demangle(name));
  if (unresolved.empty())
    return;

  std::cerr << "warning: " << host.getSourceFileName()
            << ": references CUDA-Q symbols outside the nvq++ C-API:";
  for (auto &name : unresolved)
    std::cerr << "\n  " << name;
  std::cerr << "\nlink with an existing nvq++ binary or the required CUDA-Q "
               "libraries before executing or loading into Python.\n";
}

int main(int argc, char *argv[]) {
  std::vector<const char *> args;
  bool warnUnresolvedSymbols = false;
  for (int i = 1; i < argc; ++i) {
    if (llvm::StringRef(argv[i]) == "--warn-unresolved")
      warnUnresolvedSymbols = true;
    else
      args.push_back(argv[i]);
  }
  if (args.size() != 3) {
    std::cerr << "Usage:\n\tfixup-linkage [--warn-unresolved] "
                 "<generated-LLVM-file> <LLVM-file> <output>\n";
    return 1;
  }
  const char *generatedFile = args[0];
  const char *hostFile = args[1];
  const char *outputFile = args[2];

  llvm::LLVMContext ctx;
  auto host = parse(hostFile, ctx);
  if (!host)
    return 1;
  auto generated = parse(generatedFile, ctx);
  if (!generated)
    return 1;

  // 1. Collect the functions defined and declared by the generated code.
  std::set<std::string> definedByGenerated;
  std::set<std::string> declaredByGenerated;
  for (auto &func : *generated) {
    if (func.isDeclaration())
      declaredByGenerated.insert(func.getName().str());
    else if (!func.hasLocalLinkage())
      definedByGenerated.insert(func.getName().str());
  }

  // 2. Delete the host definitions shadowed by generated code.
  bool deletedBodies = false;
  for (auto &func : *host) {
    if (func.isDeclaration() || !definedByGenerated.count(func.getName().str()))
      continue;
    func.deleteBody();
    func.setComdat(nullptr);
    if (!func.isImplicitDSOLocal())
      func.setDSOLocal(false);
    deletedBodies = true;
  }

  // 3. Run DCE to remove everything that became unreachable.
  if (deletedBodies) {
    // Mark host definitions declared in generated code so they survive DCE.
    llvm::SmallVector<llvm::GlobalValue *> keep;
    for (auto &func : *host)
      if (!func.isDeclaration() && func.isDiscardableIfUnused() &&
          declaredByGenerated.count(func.getName().str()))
        keep.push_back(&func);
    llvm::appendToCompilerUsed(*host, keep);

    llvm::LoopAnalysisManager lam;
    llvm::FunctionAnalysisManager fam;
    llvm::CGSCCAnalysisManager cgam;
    llvm::ModuleAnalysisManager mam;
    llvm::PassBuilder pb;
    pb.registerModuleAnalyses(mam);
    pb.registerCGSCCAnalyses(cgam);
    pb.registerFunctionAnalyses(fam);
    pb.registerLoopAnalyses(lam);
    pb.crossRegisterProxies(lam, fam, cgam, mam);
    llvm::ModulePassManager mpm;
    mpm.addPass(llvm::GlobalDCEPass());
    mpm.run(*host, mam);
  }

  if (llvm::verifyModule(*host, &llvm::errs())) {
    std::cerr << "fixup-linkage: invalid module after rewriting.\n";
    return 1;
  }

  if (warnUnresolvedSymbols)
    warnUnresolved(*host, *generated);

  std::error_code ec;
  llvm::raw_fd_ostream out(outputFile, ec);
  if (ec) {
    std::cerr << "fixup-linkage: cannot open " << outputFile << ": "
              << ec.message() << '\n';
    return 1;
  }
  host->print(out, nullptr);
  return 0;
}
