/// The fixup-linkage tool is used to rewrite the LLVM IR produced by clang for
/// the classical compute code such that it can be linked correctly with the
/// LLVM IR that is generated for the quantum code.
///
/// We distinguish the 'host code' (generated by standard clang from the C++
/// source) from the 'generated code' (which contains the custom kernel stubs
/// that will redirect kernel launches into the CUDA-Q runtime). Kernel entry
/// points in the generated code shadow any definitions of the same name in the
/// host code.
///
/// For every kernel in the mangled name map of the Quake file:
///   - If the generated code defines a host entry point for the kernel, the
///     host definition is considered dead. It is DCE-ed along with any code
///     only reachable from it.
///   - Otherwise, the host definition is kept and given `linkonce_odr` linkage.
///
/// Explicitly DCE-ing when possible keeps dead dependencies (e.g. the execution
/// manager) out of the object files produced by nvq++.

#include "llvm/IR/LLVMContext.h"
#include "llvm/IR/Module.h"
#include "llvm/IR/Verifier.h"
#include "llvm/IRReader/IRReader.h"
#include "llvm/Passes/PassBuilder.h"
#include "llvm/Support/SourceMgr.h"
#include "llvm/Support/raw_ostream.h"
#include "llvm/Transforms/IPO/GlobalDCE.h"
#include "llvm/Transforms/Utils/ModuleUtils.h"
#include <fstream>
#include <iostream>
#include <regex>
#include <set>
#include <string>

/// Collect all the mangled kernel names from the mangled_name_map in the Quake
/// file.
static std::set<std::string> getKernelNames(const char *quakeFile) {
  std::ifstream modFile(quakeFile);
  std::string line;
  std::set<std::string> funcs;
  std::regex mapRegex{"quake\\.mangled_name_map = [{]"};
  std::regex stringRegex{"\"(.*?)\""};
  auto rgxEnd = std::sregex_iterator();
  while (std::getline(modFile, line) && funcs.empty()) {
    auto funcsBegin = std::sregex_iterator(line.begin(), line.end(), mapRegex);
    if (funcsBegin == rgxEnd)
      continue;
    auto names = line.substr(funcsBegin->str().size() - 1);
    auto namesBegin =
        std::sregex_iterator(names.begin(), names.end(), stringRegex);
    for (std::sregex_iterator i = namesBegin; i != rgxEnd; ++i) {
      auto s = i->str();
      funcs.insert(s.substr(1, s.size() - 2));
    }
  }
  return funcs;
}

static std::unique_ptr<llvm::Module> parse(const char *file,
                                           llvm::LLVMContext &ctx) {
  llvm::SMDiagnostic err;
  auto mod = llvm::parseIRFile(file, err, ctx);
  if (!mod)
    err.print("fixup-linkage", llvm::errs());
  return mod;
}

int main(int argc, char *argv[]) {
  if (argc != 4 && argc != 5) {
    std::cerr << "Usage:\n\tfixup-linkage <Quake-file> [<generated-LLVM-file>] "
                 "<LLVM-file> <output>\n";
    return 1;
  }
  const char *quakeFile = argv[1];
  const char *generatedFile = argc == 5 ? argv[2] : nullptr;
  const char *hostFile = argv[argc - 2];
  const char *outputFile = argv[argc - 1];

  auto kernels = getKernelNames(quakeFile);
  if (kernels.empty()) {
    std::cerr << "No mangled name map in the quake file.\n";
    return 1;
  }

  llvm::LLVMContext ctx;
  auto host = parse(hostFile, ctx);
  if (!host)
    return 1;

  // 1. Identify kernels with and without definitions in the generated code
  std::set<std::string> overridden;
  std::set<std::string> requiredByGenerated;
  if (generatedFile) {
    auto generated = parse(generatedFile, ctx);
    if (!generated)
      return 1;
    for (auto &gv : generated->global_values()) {
      if (gv.isDeclaration())
        requiredByGenerated.insert(gv.getName().str());
      else if (llvm::isa<llvm::Function>(gv) &&
               kernels.count(gv.getName().str()))
        overridden.insert(gv.getName().str());
    }
  }

  // 2. Delete any kernel definitions in the host that are shadowed by generated
  // code
  bool deletedBodies = false;
  for (auto &func : *host) {
    if (func.isDeclaration() || !kernels.count(func.getName().str()))
      continue;
    if (overridden.count(func.getName().str())) {
      func.deleteBody();
      func.setComdat(nullptr);
      func.setDSOLocal(false);
      deletedBodies = true;
      continue;
    }
    // Keep the definition but allow the generated code to override it.
    if (func.hasLinkOnceODRLinkage() ||
        (func.hasWeakLinkage() && func.isDSOLocal()))
      continue;
    func.setLinkage(llvm::GlobalValue::LinkOnceODRLinkage);
    func.setDSOLocal(false);
  }

  // 3. Run DCE to remove everything that became unreachable.
  if (deletedBodies) {
    // Mark host definitions declared in generated code as used to survive DCE.
    llvm::SmallVector<llvm::GlobalValue *> keep;
    for (auto &gv : host->global_values())
      if (!gv.isDeclaration() && gv.isDiscardableIfUnused() &&
          requiredByGenerated.count(gv.getName().str()))
        keep.push_back(&gv);
    llvm::appendToCompilerUsed(*host, keep);

    llvm::LoopAnalysisManager lam;
    llvm::FunctionAnalysisManager fam;
    llvm::CGSCCAnalysisManager cgam;
    llvm::ModuleAnalysisManager mam;
    llvm::PassBuilder pb;
    pb.registerModuleAnalyses(mam);
    pb.registerCGSCCAnalyses(cgam);
    pb.registerFunctionAnalyses(fam);
    pb.registerLoopAnalyses(lam);
    pb.crossRegisterProxies(lam, fam, cgam, mam);
    llvm::ModulePassManager mpm;
    mpm.addPass(llvm::GlobalDCEPass());
    mpm.run(*host, mam);
  }

  if (llvm::verifyModule(*host, &llvm::errs())) {
    std::cerr << "fixup-linkage: invalid module after rewriting.\n";
    return 1;
  }

  std::error_code ec;
  llvm::raw_fd_ostream out(outputFile, ec);
  if (ec) {
    std::cerr << "fixup-linkage: cannot open " << outputFile << ": "
              << ec.message() << '\n';
    return 1;
  }
  host->print(out, nullptr);
  return 0;
}
